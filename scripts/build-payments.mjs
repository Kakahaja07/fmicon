// Payment logos (Visa, Mastercard, PayPal…) from the FMUI 7000 set, in three card sizes.
// They are full-colour brand marks, so they live beside the icon styles, not in them.
//   npm run payments   (also part of npm run free-icons)
// Output:
//   public/payments/<size>/<slug>.svg   served as-is: fmicon.dev/payments/md/visa.svg
//   src/content/payments.meta.ts        names, slugs and sizes for the /icons/payments page

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LIB = process.env.FMUI_LIB ?? "G:/UI Deisgn/icon-library/figma7000";
const OUT = "public/payments";
const SIZES = [
  { id: "sm", label: "Small", width: 34, height: 24 },
  { id: "md", label: "Medium", width: 46, height: 32 },
  { id: "lg", label: "Large", width: 58, height: 40 },
];

// Fix the source file names that are misspelt, and give each logo its proper name.
const RENAME = { etherium: "ethereum", lightcoin: "litecoin" };
const NAMES = {
  amex: "American Express", applepay: "Apple Pay", bitcoincash: "Bitcoin Cash", bitpay: "BitPay",
  dinersclub: "Diners Club", googlepay: "Google Pay", ideal: "iDEAL", jcb: "JCB", paypal: "PayPal",
  "shop-pay": "Shop Pay", sepa: "SEPA", qiwi: "QIWI", unionpay: "UnionPay", wechat: "WeChat Pay",
  webmoney: "WebMoney", forbrugsforeningen: "Forbrugsforeningen", elo: "Elo",
};
const nameOf = (slug) => NAMES[slug] ?? slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

// Same clean-up as the icon build: one line, 2 decimals.
const tidy = (svg) => svg.replace(/\s*\n\s*/g, "").replace(/(\d+\.\d\d)\d+/g, "$1").trim() + "\n";

const files = readdirSync(join(LIB, "payment-md")).filter((f) => f.endsWith(".svg")).sort();
const logos = files.map((f) => {
  const source = f.replace(/\.svg$/, "");
  const slug = RENAME[source] ?? source;
  return { source, slug, name: nameOf(slug) };
});

rmSync(OUT, { recursive: true, force: true });
for (const size of SIZES) {
  mkdirSync(join(OUT, size.id), { recursive: true });
  for (const logo of logos) {
    const svg = readFileSync(join(LIB, `payment-${size.id}`, `${logo.source}.svg`), "utf8");
    writeFileSync(join(OUT, size.id, `${logo.slug}.svg`), tidy(svg));
  }
}

const meta = {
  sizes: SIZES,
  logos: logos.map(({ slug, name }) => ({ slug, name })).sort((a, b) => a.name.localeCompare(b.name)),
};
writeFileSync(
  "src/content/payments.meta.ts",
  `// Generated by scripts/build-payments.mjs. Do not edit by hand.\nexport const paymentsMeta = ${JSON.stringify(meta, null, 2)} as const;\n`,
);
console.log(`✓ ${logos.length} payment logos × ${SIZES.length} sizes → ${OUT}`);
